/* || (OR) Sirve para manipular los valores booleanos, 
si uno de los valores es true */

/* && (AND) Sirve para manipular los valores booleanos,
si uno de los valores es false */

//ejemplo de OR
console.log(true || false); // la primera es true, por tanto el resultado es true
console.log(false || false); // los dos son false, por tanto el resultado es false
console.log()
//ejemplo de AND
console.log(true && false); // la primera es true, pero la segunda es false, por tanto el resultado es false
console.log(true && true); // los dos son true, por tanto el resultado es true